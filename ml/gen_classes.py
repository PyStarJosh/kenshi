"""Generate web/src/detection/classes.ts from ml/class_map.json.

Run from the repo root: uv run --group ml python ml/gen_classes.py
"""

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SOURCE = REPO_ROOT / "ml" / "class_map.json"
TARGET = REPO_ROOT / "web" / "src" / "detection" / "classes.ts"

HEADER = """// Generated by ml/gen_classes.py from ml/class_map.json. Do not edit by hand.
import type { ClassInfo } from '../core/types'

export const CLASSES: readonly ClassInfo[] = [
"""


def ts_value(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"
    return str(value)


def main() -> None:
    rows = json.loads(SOURCE.read_text(encoding="utf-8"))
    if [r["id"] for r in rows] != list(range(len(rows))):
        raise SystemExit("class ids must be 0..N-1 in order")
    lines = []
    for r in rows:
        fields = ", ".join(f"{k}: {ts_value(v)}" for k, v in r.items())
        lines.append(f"  {{ {fields} }},")
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(HEADER + "\n".join(lines) + "\n]\n", encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(REPO_ROOT)} ({len(rows)} classes)")


if __name__ == "__main__":
    main()
